import { test, expect } from '@playwright/test';
for (const theme of ['light', 'dark']) test(`Library path selection in ${theme}`, async ({page}, info) => {
  await page.setViewportSize({width:1440,height:1000});
  await page.addInitScript(t => localStorage.setItem('hololab.theme', t), theme);
  let stale = false;
  let missing = false;
  let legacy = false;
  const resource = {resource_id:'video',name:'clip.mp4',size_bytes:2048,lifecycle:'active',ingest_state:'staged',sha256:'verified',placements:[{node_id:'device',relative_path:'Footage/clip.mp4',desired_state:'present',observed_state:'ready',verified_sha256:'verified'}]};
    await page.routeWebSocket('**/*', () => {});
    await page.route('**/api/**', async route => {
      const u = new URL(route.request().url()); let body: unknown = [];
      if (u.pathname === '/api/pack-catalog') body = [{ name:'builtin/single-video-source',version:'0.1.0',manifest_hash:'test',node_ids:['device'],description:'Video source',category:[],inputs:{},outputs:{},params:{video_path:{type:'path',path_kind:'file',must_exist:true}} }];
      if (u.pathname === '/api/nodes') body = [{node_id:'device',node_name:'Test node',online:true,gpu:{count:0},packs:[],legacy_workspace_roots:[],pack_dirs:[],workspace_root:'/media'}];
      if (u.pathname === '/api/workflows/path-test') body = {workflow_id:'path-test',name:'Path picker',created_ts:1,updated_ts:1,graph:{nodes:[{id:'source',algorithm_name:'builtin/single-video-source',algorithm_version:'0.1.0',params:{},assigned_node_id:'device',position:{x:100,y:100}}],edges:[]}};
      if (u.pathname === '/api/nodes/metrics/history') body = {sample_interval_s:5,nodes:{}};
      if (u.pathname === '/api/artifacts/summary') body = {total_bytes:0,exclusive_bytes:0,artifact_count:0};
      if (u.pathname === '/api/nodes/device/paths') body = {path:'/media',parent:'/',next_offset:null,entries:[{name:'classic-stg.mp4',path:'/media/classic-stg.mp4',kind:'file',symlink:false,size:2048,modified_ts:1},{name:'renders',path:'/media/renders',kind:'directory',symlink:false,size:null,modified_ts:1}].filter(e=>e.name.startsWith(u.searchParams.get('prefix')||''))};
      if (u.pathname === '/api/nodes/device/config') body = {config:{node_name:'Test node',...(legacy ? {} : {library_root:'/custom/library'})}};
      if (u.pathname === '/api/library/folders') body = {folders:[{folder_id:'root',parent_id:null,name:''},{folder_id:'footage',parent_id:'root',name:'Footage'}]};
      if (u.pathname === '/api/library/resources') body = {total:3,resources:u.searchParams.get('folder_id')==='footage' ? [resource, {...resource,resource_id:'remote',name:'remote-only.mp4',placements:[{...resource.placements[0],node_id:'other'}]}, {...resource,resource_id:'pending',name:'pending.mp4',placements:[{...resource.placements[0],observed_state:'downloading'}]}] : []};
      if (u.pathname === '/api/library/resources/video') body = stale ? {...resource,lifecycle:'deleting'} : resource;
      if (u.pathname === '/api/nodes/device/paths' && u.searchParams.get('path') === '/custom/library/Footage') body = {entries:missing ? [] : [{name:'clip.mp4',kind:'file',size:2048,path:'/custom/library/Footage/clip.mp4'}],next_offset:null};
      await route.fulfill({json:body});
    });

  await page.goto('/w/path-test');
  await page.locator('.react-flow__node').click();
  const input = page.getByRole('combobox',{name:'video_path',exact:true});
  const open = async () => {
    await page.getByRole('button',{name:'Browse paths for video_path'}).click();
    await page.getByRole('group',{name:'Path source'}).getByRole('button',{name:'Library',exact:true}).click();
    await page.getByRole('button',{name:'▸ Footage Folder'}).click();
    await expect(page.getByRole('button',{name:'clip.mp4 2,048 B'})).toBeVisible();
  };
  await open();
  await expect(page.getByText('remote-only.mp4')).toHaveCount(0);
  await expect(page.getByText('pending.mp4')).toHaveCount(0);
  await expect(page.getByRole('navigation',{name:'Library breadcrumbs'})).toContainText('Footage');
  await page.screenshot({path:info.outputPath(`library-${theme}.png`)});
  await page.getByRole('button',{name:'clip.mp4 2,048 B'}).click();
  stale = true;
  await page.getByRole('button',{name:'Select',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('no longer ready');
  await expect(input).toHaveValue('/media');
  stale = false; missing = true;
  await page.getByRole('button',{name:'Select',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('missing or has changed');
  missing = false;
  await page.getByRole('button',{name:'Select',exact:true}).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(input).toHaveValue('/custom/library/Footage/clip.mp4');
  await page.screenshot({path:info.outputPath(`filled-${theme}.png`)});
  await input.fill('/manual/video.mp4');
  await expect(input).toHaveValue('/manual/video.mp4');
  legacy = true;
  await page.getByRole('button',{name:'Browse paths for video_path'}).click();
  await page.getByRole('group',{name:'Path source'}).getByRole('button',{name:'Library',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('Upgrade this compute node');
  await expect(page.getByRole('button',{name:'Select',exact:true})).toBeDisabled();
});
